/** Texto simulado Región/Provincia/Distrito a partir de una semilla numérica (RENIEC). */
export function obtenerUbigeoTextoSimulado(seed: number): string {
  const regiones = Object.keys(UBIGEO_SODEGA);
  if (!regiones.length) return 'Ancash/Santa/Moro';
  const region = regiones[seed % regiones.length];
  const provincias = Object.keys(UBIGEO_SODEGA[region] ?? {});
  const provincia = provincias[seed % provincias.length] ?? 'Santa';
  const distritos = UBIGEO_SODEGA[region]?.[provincia] ?? [];
  const distrito = distritos[seed % distritos.length] ?? 'Moro';
  return `${region}/${provincia}/${distrito}`;
}

/** Presenta el ubigeo como texto legible; los códigos numéricos antiguos se convierten. */
export function formatearUbigeoTexto(ubigeo: string): string {
  const texto = String(ubigeo || '').trim();
  if (!texto) return '-';
  if (/^\d+$/.test(texto)) return obtenerUbigeoTextoSimulado(parseInt(texto, 10));
  return texto;
}

